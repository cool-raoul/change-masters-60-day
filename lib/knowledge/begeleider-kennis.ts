/** Onderwerpen waarop deze regels sowieso mee moeten, ook zonder programma-vraag. */
const EXTRA_TRIGGERS =
  /\b(aandoening|ziekte|crohn|colitis|diverticulitis|diabetes|fibromyalgie|migraine|gordelroos|reuma|schildklier|kanker|zwanger\w*|borstvoeding|medicat\w*|medicijn\w*|arts|huisarts|flauwval\w*|hartklop\w*|braken|verward)/i;

export function heeftBegeleiderKennisNodig(vraag: string): boolean {
  return EXTRA_TRIGGERS.test(vraag);
}
